    teaching_academic while `research assistant professor` (71,785) was in
    researcher_early - 85,845 records split by word order alone. The library
    lists the two as ONE entry. This query would have found it automatically.

    HOW TO READ IT. Only split groups come back. Each row is one synonym group
    that lands in more than one of our professions. `members` shows what the
    library considers one job and where each piece went.

    A SPLIT IS NOT AUTOMATICALLY AN ERROR. Two cases are legitimate:
      - practitioner / trainee_clinical feed the same two audiences, so a split
        across those two changes nothing for marketing
      - researcher_early / researcher_established likewise
